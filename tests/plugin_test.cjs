const assert = require('node:assert/strict');
const fs = require('node:fs');
const model = require('../plugin/Model.js');
const now = 2000000000;
const battery = {charge:50,watts:9,health:90,cycles:100,hours:3,state:'Discharging'};
const raw = {version:1,generatedAt:now,battery,context:{ts:now,cpu:10,brightness:50,profile:'power-saver',apps:[{name:'<img src="https://invalid.test/a">',cpu:5}]},analysis:{status:'warming',matches:0},points:[{ts:now-30,watts:9},{ts:now,watts:8}],sessions:[]};
assert.equal(model.status(JSON.stringify(battery)).watts,9);
assert.equal(model.status('{'),null);
assert.equal(model.status(JSON.stringify({...battery,watts:'9'})),null);
assert.equal(model.status('x'.repeat(65537)),null);
const parsed = model.report(JSON.stringify(raw),now);
assert.ok(parsed);
assert.equal(parsed.points[0].charge,-1);
assert.equal(model.report(JSON.stringify({...raw,points:[{ts:now,watts:9,charge:67}]}),now).points[0].charge,67);
assert.equal(model.report(JSON.stringify({...raw,points:[{ts:now,watts:9,charge:101}]}),now).points[0].charge,-1);
assert.equal(parsed.context.apps[0].name,raw.context.apps[0].name);
assert.equal(model.report(JSON.stringify({...raw,generatedAt:now-1000}),now),null);
assert.equal(model.report(JSON.stringify({...raw,points:Array(121).fill(raw.points[0])}),now),null);
assert.equal(model.report(JSON.stringify({...raw,points:[{ts:now+301,watts:9}]}),now),null);
assert.equal(model.report(JSON.stringify({...raw,points:[raw.points[1],raw.points[0]]}),now),null);
assert.equal(model.report(JSON.stringify({...raw,analysis:{status:'ready'}}),now),null);
assert.equal(model.label('abc\u0000def',64),'abcdef');
const plain = fs.readFileSync(new URL('../plugin/PlainText.qml',`file://${__filename}`),'utf8');
assert.match(plain,/textFormat:\s*Text\.PlainText/);
const widget = fs.readFileSync(new URL('../plugin/Widget.qml',`file://${__filename}`),'utf8');
assert.match(widget,/tooltipText:\s*catalog\.t\("tooltip"\)/);
assert.doesNotMatch(widget,/tooltipText:[^\n]*(battery|report|context)/);
const source = fs.readFileSync(new URL('../plugin/BatteryDetails.qml',`file://${__filename}`),'utf8');
assert.doesNotMatch(source,/\bText\s*\{/);
assert.doesNotMatch(source,/ScrollView|Flickable/);
assert.match(source,/StackLayout/);
const graph=fs.readFileSync(new URL('../plugin/HistoryGraph.qml',`file://${__filename}`),'utf8');
assert.doesNotMatch(graph,/\bText\s*\{/);
const en=JSON.parse(fs.readFileSync(new URL('../plugin/i18n/en.json',`file://${__filename}`),'utf8'));
for(const match of (widget+source).matchAll(/\.t\("([^"]+)"\)/g)) assert.ok(en[match[1]],`missing ${match[1]}`);
console.log('Plugin parsing, bounds, plain-text/tooltip safety and catalog checks passed.');
